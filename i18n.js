// ── Init ──────────────────────────────────────────────────────────────────────
document.addEventListener('DOMContentLoaded', function() {
  const saved = localStorage.getItem('spineline-lang');
  if (saved && i18nTranslations[saved]) {
    setLang(saved);
  } else {
    const browser = (navigator.language || 'de').toLowerCase();
    setLang(browser.startsWith('de') ? 'de' : 'en');
  }
});
