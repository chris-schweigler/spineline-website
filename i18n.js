// ── Engine ────────────────────────────────────────────────────────────────────
function i18nT(lang, key) {
  return (i18nTranslations[lang] && i18nTranslations[lang][key])
    || (i18nTranslations['de'] && i18nTranslations['de'][key])
    || key;
}

function setLang(lang) {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = i18nT(lang, el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = i18nT(lang, el.getAttribute('data-i18n-html'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = i18nT(lang, el.getAttribute('data-i18n-placeholder'));
  });
  const titleEl = document.querySelector('[data-i18n-title]');
  if (titleEl) titleEl.textContent = i18nT(lang, titleEl.getAttribute('data-i18n-title'));

  document.documentElement.lang = lang;

  document.querySelectorAll('.lang-btn').forEach(btn => btn.classList.remove('active'));
  const active = document.getElementById('btn-' + lang);
  if (active) active.classList.add('active');

  localStorage.setItem('spineline-lang', lang);
}

